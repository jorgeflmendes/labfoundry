from copy import deepcopy
from pathlib import Path
from typing import Any

import pytest

from labfoundry.compiler.compiler import ScenarioCompiler
from labfoundry.errors import CompilationError
from labfoundry.schema.loader import load_scenario
from labfoundry.schema.scenario import ScenarioSpec


def test_unknown_event_actor_is_rejected(scenario_data: dict[str, Any]) -> None:
    raw = scenario_data
    events = raw["events"]
    assert isinstance(events, list)
    first = events[0]
    assert isinstance(first, dict)
    first["from"] = "typo-workstation"
    first.pop("select")

    spec = ScenarioSpec.model_validate(raw)
    with pytest.raises(CompilationError, match="unknown node/alias"):
        ScenarioCompiler().compile(spec)


def test_unknown_traffic_target_is_rejected(scenario_data: dict[str, Any]) -> None:
    raw = scenario_data
    traffic = raw["traffic"]
    assert isinstance(traffic, dict)
    profiles = traffic["profiles"]
    assert isinstance(profiles, dict)
    office = profiles["office-user"]
    assert isinstance(office, dict)
    actions = office["actions"]
    assert isinstance(actions, list)
    action = actions[0]
    assert isinstance(action, dict)
    action["to"] = "typo-dns"

    spec = ScenarioSpec.model_validate(raw)
    with pytest.raises(CompilationError, match="unknown node group"):
        ScenarioCompiler().compile(spec)


def test_selector_alias_cannot_overwrite_group(scenario_data: dict[str, Any]) -> None:
    raw = scenario_data
    events = raw["events"]
    assert isinstance(events, list)
    first = events[0]
    assert isinstance(first, dict)
    selector = first["select"]
    assert isinstance(selector, dict)
    selector["as"] = "ws"

    spec = ScenarioSpec.model_validate(raw)
    with pytest.raises(CompilationError, match="collides"):
        ScenarioCompiler().compile(spec)


def test_generated_node_names_cannot_collide(scenario_data: dict[str, Any]) -> None:
    raw = scenario_data
    network = raw["network"]
    assert isinstance(network, dict)
    nodes = network["nodes"]
    assert isinstance(nodes, dict)
    nodes["ws-01"] = deepcopy(nodes["dns"])

    spec = ScenarioSpec.model_validate(raw)
    with pytest.raises(CompilationError, match="generated by both"):
        ScenarioCompiler().compile(spec)


def test_duplicate_capture_on_same_link_is_rejected(scenario_data: dict[str, Any]) -> None:
    raw = scenario_data
    captures = raw["captures"]
    assert isinstance(captures, list)
    duplicate = deepcopy(captures[0])
    assert isinstance(duplicate, dict)
    duplicate["name"] = "users-perimeter-copy"
    captures.append(duplicate)

    spec = ScenarioSpec.model_validate(raw)
    with pytest.raises(CompilationError, match="same GNS3 link"):
        ScenarioCompiler().compile(spec)


def test_absolute_event_before_scenario_start_is_rejected(scenario_data: dict[str, Any]) -> None:
    raw = scenario_data
    events = raw["events"]
    assert isinstance(events, list)
    first = events[0]
    assert isinstance(first, dict)
    first["at"] = "2025-04-16T09:17:32+01:00"

    spec = ScenarioSpec.model_validate(raw)
    with pytest.raises(CompilationError, match="before scenario start"):
        ScenarioCompiler().compile(spec)


def test_seed_override_obeys_same_range_as_dsl(scenario_path: Path) -> None:
    spec = load_scenario(scenario_path)
    with pytest.raises(CompilationError, match=r"2\^63-1"):
        ScenarioCompiler().compile(spec, seed=2**63)
